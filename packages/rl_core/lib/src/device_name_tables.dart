// Generated canonical composition lookup: (starter << 21) | combining -> composite
final Map<int, int> _canonicalCompositions = () {
  final map = <int, int>{};
  for (final entry in _canonicalDecompositions.entries) {
    if (entry.value.length == 2) {
      final starter = entry.value[0];
      final combining = entry.value[1];
      final key = (starter << 21) | combining;
      map[key] = entry.key;
    }
  }
  return map;
}();

