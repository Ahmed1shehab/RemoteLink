/// Partial Unicode NFC (Normalization Form C) normalisation.
///
/// Follows the shape of Unicode Standard Annex #15 — canonical decomposition,
/// canonical ordering by combining class, then canonical composition — and
/// implements the Hangul algorithm in full, since that part is algorithmic
/// rather than table-driven.
///
/// **It is deliberately not complete, and must not be treated as if it were.**
/// Full NFC requires the entire canonical decomposition table from the Unicode
/// Character Database, which runs to thousands of entries. The table here
/// covers the Latin, Greek, and Cyrillic precomposed forms that appear in
/// device names in practice. A character outside it passes through unchanged
/// rather than being normalised.
///
/// That is an acceptable trade for a display name, where the consequence of a
/// miss is two names that look alike being stored as distinct strings. It is
/// **not** acceptable for anything where two spellings resolving to one
/// identity matters — a filename, a path, or a trust key. Do not reach for this
/// function in those places; see the note in `sanitiseDeviceName` and the
/// separate filename sanitiser in `rl_protocol`, which has its own
/// normalisation with different requirements.

const int _sBase = 0xAC00;
const int _lBase = 0x1100;
const int _vBase = 0x1161;
const int _tBase = 0x11A7;
const int _lCount = 19;
const int _vCount = 21;
const int _tCount = 28;
const int _nCount = _vCount * _tCount; // 588
const int _sCount = _lCount * _nCount; // 11172

/// Normalises [input] to Unicode Normalization Form C (NFC).
String normalizeNfc(String input) {
  if (input.isEmpty) return input;
  final decomposed = _decompose(input);
  final composed = _compose(decomposed);
  return String.fromCharCodes(composed);
}

/// Step 1: Canonical Decomposition (NFD) + Canonical Ordering.
List<int> _decompose(String input) {
  final result = <int>[];

  for (final rune in input.runes) {
    _decomposeRecursive(rune, result);
  }

  _canonicalOrder(result);
  return result;
}

void _decomposeRecursive(int rune, List<int> out) {
  // Hangul syllable decomposition
  if (rune >= _sBase && rune < _sBase + _sCount) {
    final sIndex = rune - _sBase;
    final lIndex = sIndex ~/ _nCount;
    final vIndex = (sIndex % _nCount) ~/ _tCount;
    final tIndex = sIndex % _tCount;

    out.add(_lBase + lIndex);
    out.add(_vBase + vIndex);
    if (tIndex > 0) {
      out.add(_tBase + tIndex);
    }
    return;
  }

  final decomp = _canonicalDecompositions[rune];
  if (decomp != null) {
    for (final part in decomp) {
      _decomposeRecursive(part, out);
    }
  } else {
    out.add(rune);
  }
}

/// Sorts sequences of combining characters by Canonical Combining Class (CCC).
void _canonicalOrder(List<int> codePoints) {
  for (var i = 1; i < codePoints.length; i++) {
    final ccc = _getCanonicalCombiningClass(codePoints[i]);
    if (ccc == 0) continue;

    var j = i;
    while (j > 0) {
      final prevCcc = _getCanonicalCombiningClass(codePoints[j - 1]);
      if (prevCcc == 0 || prevCcc <= ccc) break;

      // Swap
      final temp = codePoints[j];
      codePoints[j] = codePoints[j - 1];
      codePoints[j - 1] = temp;
      j--;
    }
  }
}

/// Step 2: Canonical Composition (NFC).
List<int> _compose(List<int> codePoints) {
  if (codePoints.length <= 1) return codePoints;

  final result = <int>[];
  var starterIndex = 0;
  result.add(codePoints[0]);
  var prevCcc = _getCanonicalCombiningClass(codePoints[0]);

  for (var i = 1; i < codePoints.length; i++) {
    final current = codePoints[i];
    final currentCcc = _getCanonicalCombiningClass(current);

    if (result.isNotEmpty) {
      final starter = result[starterIndex];

      // 1. Hangul L + V -> LV
      if (starter >= _lBase &&
          starter < _lBase + _lCount &&
          current >= _vBase &&
          current < _vBase + _vCount &&
          prevCcc == 0) {
        final lIndex = starter - _lBase;
        final vIndex = current - _vBase;
        final lv = _sBase + (lIndex * _vCount + vIndex) * _tCount;
        result[starterIndex] = lv;
        continue;
      }

      // 2. Hangul LV + T -> LVT
      if (starter >= _sBase &&
          starter < _sBase + _sCount &&
          (starter - _sBase) % _tCount == 0 &&
          current > _tBase &&
          current < _tBase + _tCount &&
          prevCcc == 0) {
        final tIndex = current - _tBase;
        result[starterIndex] = starter + tIndex;
        continue;
      }

      // 3. General canonical composition:
      // A character C is not blocked from starter S if:
      // - currentCcc > prevCcc (or prevCcc == 0)
      if ((prevCcc == 0 || currentCcc > prevCcc) &&
          !_isCompositionExcluded(current)) {
        final composite = _canonicalComposition(starter, current);
        if (composite != null) {
          result[starterIndex] = composite;
          continue;
        }
      }
    }

    // Append current character and update starter/prevCcc
    result.add(current);
    if (currentCcc == 0) {
      starterIndex = result.length - 1;
      prevCcc = 0;
    } else {
      prevCcc = currentCcc;
    }
  }

  return result;
}

int _getCanonicalCombiningClass(int codePoint) =>
    _canonicalCombiningClasses[codePoint] ?? 0;

int? _canonicalComposition(int starter, int combining) {
  final key = (starter << 21) | combining;
  return _canonicalCompositions[key];
}

bool _isCompositionExcluded(int codePoint) =>
    _compositionExclusions.contains(codePoint);

